"""Validate raw ThinQ timer profiles without inventing unsupported controls."""
import math

class TimerUnsupported(ValueError):
    pass

def timer_profile(profile):
    result = profile.get("property", {}).get("sleepTimer", {})
    return result if isinstance(result, dict) else {}

def allows(spec, value):
    if not isinstance(spec, dict) or "w" not in spec.get("mode", []):
        return False
    values = spec.get("value", {}).get("w")
    if spec.get("type") in ("enum", "list"):
        return isinstance(values, list) and value in values
    # Some ThinQ profiles declare a writable number with no published range.
    # Only bounded non-negative integers generated by set_payload reach here.
    if spec.get("type") == "number" and values is None:
        return type(value) is int and 0 <= value <= 24
    if spec.get("type") == "number" and isinstance(values, list):
        return type(value) is int and value in values
    if spec.get("type") not in ("range", "number") or not isinstance(values, dict):
        return False
    try:
        lo, hi = values["min"], values["max"]
        step = values.get("step", 1)
        return (step > 0 and lo <= value <= hi and value not in values.get("except", [])
                and math.isclose((value - lo) / step, round((value - lo) / step), abs_tol=1e-8))
    except (KeyError, TypeError, ValueError, ZeroDivisionError):
        return False

def set_payload(profile, minutes):
    if isinstance(minutes, bool) or not isinstance(minutes, int) or not 1 <= minutes <= 1440:
        raise ValueError("Minutes must be an integer from 1 to 1440.")
    props = timer_profile(profile)
    hour, minute = divmod(minutes, 60)
    if not allows(props.get("relativeHourToStop"), hour):
        raise TimerUnsupported("LG profile does not permit this timer hour value.")
    payload = {"relativeHourToStop": hour}
    minute_spec = props.get("relativeMinuteToStop")
    if isinstance(minute_spec, dict) and "w" in minute_spec.get("mode", []):
        if not allows(minute_spec, minute):
            raise TimerUnsupported("LG profile does not permit this timer minute value.")
        payload["relativeMinuteToStop"] = minute
    elif minute:
        raise TimerUnsupported("此設備僅能設定整數小時，例如 60、120、180 分鐘。")
    flag = props.get("relativeStopTimer")
    # DHUM_231006_WW accepts UNSET only on this flag. Set the writable hour
    # field alone; never send SET when it is absent from the write enum.
    if allows(flag, "SET"):
        payload["relativeStopTimer"] = "SET"
    return {"sleepTimer": payload}

def cancel_payload(profile):
    props = timer_profile(profile)
    if not allows(props.get("relativeStopTimer"), "UNSET"):
        raise TimerUnsupported(
            "LG profile does not expose writable UNSET cancellation. "
            "Cancel in the ThinQ app; zero is not assumed to mean cancel.")
    return {"sleepTimer": {"relativeStopTimer": "UNSET"}}

def snapshot(state):
    timer = state.get("sleepTimer", {})
    if not isinstance(timer, dict):
        timer = {}
    hour = timer.get("relativeHourToStop")
    minute = timer.get("relativeMinuteToStop")
    flag = timer.get("relativeStopTimer")
    # Missing values remain unknown; do not manufacture remaining time.
    remaining = None
    if flag == "SET" and isinstance(hour, int) and not isinstance(hour, bool) and isinstance(minute, int) and not isinstance(minute, bool):
        if hour >= 0 and 0 <= minute <= 59:
            remaining = hour * 60 + minute
    return {"timer_state": flag, "remaining_minutes": remaining, "sleepTimer": timer}
